"""Generate entry-probe patch tables from targets.csv (F299 uncovered app functions).

For each target VA:
  - disassemble forward until an instruction boundary >= 5 bytes -> L (patch length)
  - reject if the function is shorter than 5 bytes, L > 24, any relative branch is
    inside [0,L), or a direct call/jmp into (target, target+L) exists in .text
Outputs targets.inc (C tables) + targets.json (manifest) next to this file.

usage: python tools/entryprobe/gen_targets.py [targets.csv] [--exe bin/gametop/game.exe]
       [--out-inc PATH] [--out-json PATH]   # 自定义目标集时避免覆盖 F299 基线表
"""
import argparse
import csv
import json
import os
import struct
import sys

import capstone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


class PE:
    """minimal PE32 reader: sections + VA mapping (same one used by the F299 probes)."""

    def __init__(self, path):
        self.d = open(path, "rb").read()
        pe = struct.unpack_from("<I", self.d, 0x3C)[0]
        nsec = struct.unpack_from("<H", self.d, pe + 6)[0]
        optsz = struct.unpack_from("<H", self.d, pe + 20)[0]
        opt = pe + 24
        self.ib = struct.unpack_from("<I", self.d, opt + 28)[0]
        self.secs = []
        so = opt + optsz
        for i in range(nsec):
            o = so + i * 40
            name = self.d[o:o + 8].rstrip(b"\0").decode()
            vsz, va, rsz, ro = struct.unpack_from("<IIII", self.d, o + 8)
            self.secs.append((name, self.ib + va, vsz, ro, rsz))

    def off(self, va):
        for _n, sva, vsz, ro, rsz in self.secs:
            if sva <= va < sva + max(vsz, rsz):
                return ro + (va - sva)

    def rd(self, va, n):
        o = self.off(va)
        return self.d[o:o + n] if o is not None else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", nargs="?", default=os.path.join(HERE, "targets.csv"))
    ap.add_argument("--exe", default=os.path.join(ROOT, "bin/gametop/game.exe"))
    ap.add_argument("--out-inc", default=os.path.join(HERE, "targets.inc"))
    ap.add_argument("--out-json", default=os.path.join(HERE, "targets.json"))
    args = ap.parse_args()

    pe = PE(args.exe)
    text = [s for s in pe.secs if s[0] == ".text"][0]
    _, tva, tvsz, tro, trz = text
    blob = pe.d[tro:tro + trz]
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True

    rows = list(csv.DictReader(open(args.csv)))
    sizes = {int(r["rva"], 16): int(r["size"]) for r in rows}
    targets = sorted(sizes)

    inner = set()
    pos = 0
    while pos < len(blob):
        prog = False
        for ins in md.disasm(memoryview(blob)[pos:], tva + pos):
            prog = True
            pos = ins.address - tva + ins.size
            if ins.mnemonic in ("call", "jmp") and ins.op_str.startswith("0x"):
                inner.add(int(ins.op_str, 16))
        if not prog:
            pos += 1

    out, skipped = [], []
    for va in targets:
        fsize = sizes[va]
        code = pe.rd(va, min(32, max(fsize, 1)))
        L, ok, why = 0, True, ""
        for ins in md.disasm(code, va):
            if ins.mnemonic in ("jmp", "call", "je", "jne", "jb", "jbe", "ja", "jae", "jl", "jle", "jg", "jge",
                                "js", "jns", "jo", "jno", "jp", "jnp", "jcxz", "jecxz", "loop", "loope", "loopne"):
                ok, why = False, "relbranch:" + ins.mnemonic
                break
            L = ins.address + ins.size - va
            if L >= 5:
                break
        if L < 5:
            ok, why = False, why or f"short(L={L})"
        if L > 24:
            ok, why = False, "long"
        if ok and L > fsize:
            ok, why = False, f"beyond-size(L={L},size={fsize})"
        if ok and any(va < x < va + L for x in inner):
            ok, why = False, "interior-entry"
        (out if ok else skipped).append({"va": va, "len": L} if ok else {"va": va, "why": why})

    os.makedirs(os.path.dirname(os.path.abspath(args.out_json)), exist_ok=True)
    json.dump({"targets": out, "skipped": skipped}, open(args.out_json, "w"), indent=1)
    lines = ["/* generated by tools/entryprobe/gen_targets.py */",
             f"#define EP_N {len(out)}",
             "static const unsigned int g_va[EP_N] = {"]
    lines += ["  " + ",".join(f"0x{t['va']:08x}" for t in out[i:i + 8]) + "," for i in range(0, len(out), 8)]
    lines += ["};", "static const unsigned char g_len[EP_N] = {"]
    lines += ["  " + ",".join(str(t["len"]) for t in out[i:i + 16]) + "," for i in range(0, len(out), 16)]
    lines += ["};"]
    open(args.out_inc, "w", newline="\r\n").write("\n".join(lines) + "\n")
    print(f"targets={len(out)} skipped={len(skipped)}")
    for s in skipped:
        print(f"  skip {s['va']:#08x} {s['why']}")


if __name__ == "__main__":
    main()
